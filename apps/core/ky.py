WEEKDAYS = {"понедельник": "дүйшөмбү", "вторник": "шейшемби", "среда": "шаршемби", "четверг": "бейшемби",
            "пятница": "жума", "суббота": "ишемби", "воскресенье": "жекшемби"}
MONTHS = {"января": "январь", "февраля": "февраль", "марта": "март", "апреля": "апрель", "мая": "май",
          "июня": "июнь", "июля": "июль", "августа": "август", "сентября": "сентябрь", "октября": "октябрь",
          "ноября": "ноябрь", "декабря": "декабрь"}

_DATE_RE = re.compile(r"(%s), (\d{1,2}) (%s) (\d{4})" % ("|".join(WEEKDAYS), "|".join(MONTHS)))
_RULES = [
    (re.compile(r"вернуть до (\d{2}\.\d{2}\.\d{4})"), r"\1 чейин кайтарыңыз"),
    (re.compile(r"(?<![А-Яа-яЁё])до (\d{1,2}\.\d{2}(?:\.\d{4})?)"), r"\1 чейин"),
    (re.compile(r"Попробуйте снова через (\d+) мин\."), r"\1 мин. өткөндөн кийин кайра аракет кылыңыз."),
]
_MAP = dict(PAIRS)
_KEY_RE = re.compile("|".join(re.escape(k) for k in sorted(_MAP, key=len, reverse=True)))


def _date(m):
    return "%s, %s %s %s" % (WEEKDAYS[m.group(1)], m.group(2), MONTHS[m.group(3)], m.group(4))


def translate(html):
    """Русский HTML → кыргызский (по словарю PAIRS)."""
    html = _DATE_RE.sub(_date, html)
    for rx, repl in _RULES:
        html = rx.sub(repl, html)
    return _KEY_RE.sub(lambda m: _MAP[m.group(0)], html)
